# Bundles src/ (in src/manifest.txt order) into one Luau chunk that returns the UI table.
# Dot-source this file, then call Get-DrawuiBundle.
function Get-DrawuiBundle {
    param([Parameter(Mandatory = $true)][string]$ProjectPath)
    $src = Join-Path $ProjectPath 'src'
    $lines = [IO.File]::ReadAllLines((Join-Path $src 'manifest.txt'))
    $sb = New-Object Text.StringBuilder
    [void]$sb.AppendLine('-- Drawui | retained Roblox-style UI rendered with Drawing.new (Roblox executors).')
    [void]$sb.AppendLine('-- GENERATED by build.ps1 from src/ - edit the modules in src/, not this file.')
    [void]$sb.AppendLine('-- Docs: https://docs.potassium.pro/api-reference/introduction')
    [void]$sb.AppendLine('local UI, ctx = {}, {}')
    foreach ($line in $lines) {
        $module = $line.Trim()
        if ($module -eq '' -or $module.StartsWith('#')) { continue }
        $path = Join-Path $src $module
        if (-not (Test-Path $path)) { throw "Missing module in manifest: $module" }
        $code = [IO.File]::ReadAllText($path).TrimEnd()
        [void]$sb.AppendLine("-- ==== $module ====")
        [void]$sb.AppendLine(';(function()')
        [void]$sb.AppendLine($code)
        [void]$sb.AppendLine('end)()(UI, ctx)')
    }
    [void]$sb.AppendLine('return UI')
    return $sb.ToString()
}
